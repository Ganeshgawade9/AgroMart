import logging
from django.conf import settings
from notifications.sms import normalize_phone

logger = logging.getLogger(__name__)

_app = None


def get_firebase_app():
    global _app
    if _app is not None:
        return _app
    try:
        import firebase_admin
        from firebase_admin import credentials
        if not firebase_admin._apps:
            import os
            cred_path = getattr(settings, 'FIREBASE_CREDENTIALS_PATH', '')
            candidate_paths = []
            if cred_path:
                candidate_paths.append(cred_path if os.path.isabs(cred_path) else os.path.join(settings.BASE_DIR, cred_path))
            candidate_paths.append(os.path.join(settings.BASE_DIR, 'firebase-credentials.json'))
            candidate_paths.append(os.path.join(settings.BASE_DIR, 'agroconnect-596b2-firebase-adminsdk-fbsvc-46a6229aa4.json'))

            found_path = next((p for p in candidate_paths if os.path.exists(p)), None)
            if found_path:
                cred = credentials.Certificate(found_path)
                _app = firebase_admin.initialize_app(cred)
            else:
                _app = firebase_admin.initialize_app()
        else:
            _app = firebase_admin.get_app()
        return _app
    except Exception as e:
        logger.info("Firebase Admin initialized without credentials file: %s", e)
        return None


def verify_firebase_id_token(id_token, expected_phone=None):
    """Verify a Firebase ID Token generated by Firebase Phone Auth.

    Returns (True, phone_number) if valid, or (False, None) if invalid/expired.
    """
    if not id_token:
        return False, None
    try:
        from firebase_admin import auth
        get_firebase_app()
        decoded = auth.verify_id_token(id_token)
        phone = decoded.get('phone_number', '')  # E.164 format, e.g. '+919022324360'
        clean = normalize_phone(phone)
        if expected_phone and clean != normalize_phone(expected_phone):
            logger.warning("Firebase token phone %s does not match expected %s", clean, expected_phone)
            return False, None
        return True, clean
    except Exception as e:
        logger.warning("Firebase ID token verification failed: %s", e)
        return False, None
