import api from './axios';
export const getProducts = (params) => api.get('/products/', { params });
export const getProduct = (id) => api.get(`/products/${id}/`);
export const getFeatured = () => api.get('/products/featured/');
export const getCategories = () => api.get('/products/categories/');
export const getBrands = () => api.get('/products/brands/');
export const getMyProducts = () => api.get('/products/my-products/');
export const createProduct = (data) => api.post('/products/my-products/', data, { headers: { 'Content-Type': 'multipart/form-data' } });
export const updateProduct = (id, data) => api.patch(`/products/my-products/${id}/`, data, { headers: { 'Content-Type': 'multipart/form-data' } });
export const deleteProduct = (id) => api.delete(`/products/my-products/${id}/`);
export const addReview = (productId, data) => api.post(`/products/${productId}/reviews/`, data);
export const getCart = () => api.get('/products/cart/');
export const addToCart = (data) => api.post('/products/cart/', data);
export const updateCartItem = (id, data) => api.patch(`/products/cart/${id}/`, data);
export const removeFromCart = (id) => api.delete(`/products/cart/${id}/`);
export const clearCart = () => api.delete('/products/cart/clear/');
export const getWishlist = () => api.get('/products/wishlist/');
export const addToWishlist = (productId) => api.post('/products/wishlist/', { product_id: productId });
export const removeFromWishlist = (id) => api.delete(`/products/wishlist/${id}/`);
